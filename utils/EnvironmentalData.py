def Hearing_threshold(f, info):
    """
    Compute hearing threshold based on the given parameters.
    f : frequency in kHz (numpy array)
    info : dictionary with keys 'T_o', 'A', 'B', 'F1', 'F2'
    """
    T_o = info['T_o']
    A = info['A']
    B = info['B']
    F1 = info['F1']
    F2 = info['F2']
    T = T_o + A * np.log10(1 + F1 / f) + (f / F2) ** B
    return T

